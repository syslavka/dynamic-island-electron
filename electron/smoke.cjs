const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const { globalShortcut } = require('electron');
const delay = (ms) => new Promise((resolve) => setTimeout(resolve, ms));
async function until(check, label) {
  const deadline = Date.now() + 12000;
  while (Date.now() < deadline) { if (await check()) return; await delay(100); }
  throw new Error(`Timed out: ${label}`);
}
module.exports = async ({ app, overlay, openSettings, shortcuts, getSettings, getRegions, setMedia, readNativeMedia, recordingPath }) => {
  const evaluate = (code) => overlay.webContents.executeJavaScript(code, true);
  await until(() => evaluate('Boolean(window.desktop && document.querySelector(".island-shell"))'), 'overlay render');
  console.log('Renderer scale:', await evaluate('devicePixelRatio'));
  assert.equal(overlay.isAlwaysOnTop(), true);
  assert.equal(overlay.isResizable(), false);
  assert.match(overlay.getBackgroundColor(), /^#000000(?:00)?$/);
  assert.equal(await evaluate('document.querySelector(".studio-layout") === null'), true);
  assert.equal(await evaluate('getComputedStyle(document.querySelector(".theme-root")).backgroundColor'), 'rgba(0, 0, 0, 0)');
  assert.equal(await evaluate('document.querySelector(".island-trigger").getAttribute("aria-expanded")'), 'false');
  await until(() => getRegions().length >= 1, 'native hit region');
  const compactWidth = getRegions()[0].width;
  let initialImage;
  await until(async () => { try { initialImage = await overlay.webContents.capturePage(); return !initialImage.isEmpty(); } catch { return false; } }, 'first composited frame');
  const outside = initialImage.crop({ x: 4, y: initialImage.getSize().height - 10, width: 8, height: 8 }).toBitmap();
  assert.ok(outside.every((value, index) => index % 4 !== 3 || value === 0), 'unused renderer pixels have zero alpha');
  if (process.argv.includes('--idle-check')) {
    await delay(6500);
    assert.equal(overlay.isVisible(), true);
    assert.equal(await evaluate('getComputedStyle(document.querySelector(".island-shell")).opacity'), '1');
    assert.equal(await evaluate('document.querySelector(".island-shell").classList.contains("clock-only")'), true);
    assert.match(await evaluate('document.querySelector(".trigger-compact").innerText.trim()'), /^\d{2}:\d{2}$/);
    assert.equal(await evaluate('document.querySelector(".trigger-compact .compact-leading") === null && document.querySelector(".trigger-compact .compact-dot") === null'), true);
    console.log('PASS: idle clock remains fully visible, contains only time, no auto-hide');
    app.quit(); return;
  }
  await evaluate('document.querySelector(".island-trigger").click()');
  await until(() => evaluate('document.querySelector(".island-shell").classList.contains("expanded")'), 'expand');
  await delay(750);
  assert.ok(getRegions()[0].width > compactWidth, 'hit region follows expansion');
  assert.equal(await evaluate('document.querySelector(".clock-module") !== null'), true);
  assert.equal(globalShortcut.isRegistered(shortcuts.island), true);
  assert.equal(globalShortcut.isRegistered(shortcuts.settings), true);
  await evaluate('document.querySelector(".island-trigger").click()');
  await delay(600);
  const center = await evaluate('(() => { const rect = document.querySelector(".island-trigger").getBoundingClientRect(); return { x: Math.round(rect.x + rect.width / 2), y: Math.round(rect.y + rect.height / 2) }; })()');
  overlay.webContents.sendInputEvent({ type: 'mouseDown', ...center, button: 'left', clickCount: 1 });
  await delay(450);
  overlay.webContents.sendInputEvent({ type: 'mouseUp', ...center, button: 'left', clickCount: 1 });
  await delay(200);
  await until(() => evaluate('document.querySelector(".island-trigger").getAttribute("aria-expanded") === "true"'), 'hold expands without release collapsing');
  console.log('PASS: transparent native overlay, hit regions, clock, global shortcuts');

  await evaluate(`document.querySelector('.island-module-tabs [title="Focus timer"]').click()`);
  await until(() => evaluate('Boolean(document.querySelector(".timer-presets"))'), 'timer module');
  await evaluate('document.querySelector(".timer-presets button").click()');
  await delay(100);
  await evaluate('document.querySelector(".timer-buttons .primary").click()');
  await delay(100);
  await evaluate('document.querySelector(".island-trigger").click()');
  await delay(1200);
  const compactTimer = await evaluate('document.querySelector(".island-trigger").innerText');
  assert.match(compactTimer, /00:5[6-9]/);
  await evaluate('document.querySelector(".island-trigger").click()');
  await delay(200);
  const fixture = { available: true, title: 'Smoke test track', artist: 'Test player', album: '', duration: 180, position: 30, playing: true, canPlay: true, canPause: true, canNext: true, canPrevious: true, canSeek: true };
  setMedia(fixture);
  await until(() => evaluate('document.querySelector(".media-track h3")?.textContent === "Smoke test track"'), 'automatic music after interactions');
  await until(() => getRegions().length >= 2, 'secondary native region');
  await delay(650);
  await fs.mkdir(path.dirname(recordingPath), { recursive: true });
  await fs.writeFile(path.join(path.dirname(recordingPath), 'desktop-split.png'), (await overlay.webContents.capturePage()).toPNG());
  await evaluate('document.querySelector(".secondary-trigger").click()');
  await until(() => evaluate('document.querySelector(".secondary-island").classList.contains("secondary-expanded")'), 'secondary expansion');
  for (let frame = 0; frame < 6; frame++) {
    await delay(40);
    assert.ok(getRegions().length >= 2, 'secondary native region persists throughout the morph');
  }
  await delay(650);
  await evaluate('document.querySelector(\'.secondary-controls [aria-label="Pause timer"]\').click()');
  await delay(300);
  const pausedTime = await evaluate('document.querySelector(".secondary-time").textContent');
  await delay(650);
  assert.equal(await evaluate('document.querySelector(".secondary-time").textContent'), pausedTime);
  await evaluate('document.querySelector(\'.secondary-controls [aria-label="Resume timer"]\').click()');
  await fs.writeFile(path.join(path.dirname(recordingPath), 'desktop-secondary.png'), (await overlay.webContents.capturePage()).toPNG());
  const originalBounds = overlay.getBounds();
  const originalScale = await evaluate('document.querySelector(".theme-root").style.getPropertyValue("--island-scale")');
  for (const width of [480, 600]) for (const scale of [.8, 1.15]) {
    overlay.setBounds({ ...originalBounds, width });
    await evaluate(`document.querySelector('.theme-root').style.setProperty('--island-scale', '${scale}')`);
    await delay(550);
    const fits = await evaluate(`Array.from(document.querySelectorAll('[data-hit-region="true"]')).every(element => { const r = element.getBoundingClientRect(); return r.left >= -1 && r.right <= innerWidth + 1 && r.top >= -1 && r.bottom <= innerHeight + 1; })`);
    assert.equal(fits, true, `both islands fit width ${width}, scale ${scale}`);
    assert.ok(getRegions().length >= 2, 'both regions survive layout changes');
  }
  overlay.setBounds(originalBounds);
  await evaluate(`document.querySelector('.theme-root').style.setProperty('--island-scale', ${JSON.stringify(originalScale)})`);
  console.log('PASS: both islands fit 480/600 DIP at 80%/115% app scale');
  await evaluate('document.querySelector(".secondary-trigger").click()');
  setMedia({ ...fixture, playing: false });
  await until(() => evaluate('Boolean(document.querySelector(".timer-module"))'), 'restore timer on pause');
  setMedia(fixture);
  await until(() => evaluate('Boolean(document.querySelector(".media-track"))'), 'repeat automatic music');
  setMedia({ available: false });
  await until(() => evaluate('Boolean(document.querySelector(".timer-module"))'), 'restore after session disappears');
  await evaluate(`document.querySelector('[aria-label="Reset timer"]').click()`);
  console.log('PASS: real timer, repeated automatic music/restore, secondary controls and native regions');
  await evaluate(`(async () => { for (const title of ['Music & media','Battery','Focus timer','Часы']) { document.querySelector('.island-module-tabs [title="' + title + '"]').click(); await new Promise(resolve => setTimeout(resolve, 22)); } })()`);
  await until(() => evaluate('document.querySelector("[data-displayed-activity]").dataset.displayedActivity === "clock" && !document.querySelector(".activity-leaving")'), 'rapid navigation settles to newest activity');

  openSettings();
  await until(async () => {
    const win = getSettings();
    if (!win || win.webContents.isLoading()) return false;
    return win.webContents.executeJavaScript('Boolean(document.querySelector(".desktop-theme-options"))');
  }, 'settings window');
  await getSettings().webContents.executeJavaScript('document.querySelectorAll(".desktop-theme-options button")[1].click()');
  await until(() => evaluate('document.querySelector(".theme-root").dataset.islandTheme === "dark"'), 'cross-window settings sync');
  const qa = path.join(__dirname, '..', '.qa');
  await fs.mkdir(qa, { recursive: true });
  await delay(500);
  await fs.writeFile(path.join(qa, 'desktop-settings.png'), (await getSettings().webContents.capturePage()).toPNG());
  getSettings().close();
  await until(() => !getSettings(), 'close settings');
  openSettings();
  await until(async () => {
    const win = getSettings();
    if (!win || win.webContents.isLoading()) return false;
    return win.webContents.executeJavaScript('document.querySelector(".theme-root")?.dataset.islandTheme === "dark"');
  }, 'settings persist after reopening');
  const system = await getSettings().webContents.executeJavaScript('window.desktop.getSystem()');
  assert.equal(system.nativeGlass, false, 'DWM backdrop is never attached to the alpha window');
  assert.ok(system.battery === null || (system.battery >= 0 && system.battery <= 100));
  assert.equal(typeof system.onBattery, 'boolean');
  console.log('PASS: separate settings window, live synchronization, persisted theme, Windows power data');

  await getSettings().webContents.executeJavaScript('document.querySelectorAll(".desktop-theme-options button")[0].click()');
  await until(() => evaluate('document.querySelector(".theme-root").dataset.islandTheme === "glass"'), 'restore glass theme');
  await evaluate(`document.querySelector('.island-module-tabs [title="Часы"]').click()`);
  await delay(750);
  await fs.writeFile(path.join(qa, 'desktop-island.png'), (await overlay.webContents.capturePage()).toPNG());
  assert.equal(await evaluate('document.querySelector(".theme-root").dataset.theme'), 'dark');
  await evaluate(`document.querySelector('.island-module-tabs [title="Music & media"]').click()`);
  await until(() => evaluate('Boolean(document.querySelector(".media-track"))'), 'music module');
  const media = await readNativeMedia();
  assert.equal(typeof media.available, 'boolean');
  if (media.available) {
    assert.equal(typeof media.title, 'string');
    assert.ok(Number.isFinite(media.position));
    assert.ok(!media.artwork || media.artwork.startsWith('data:image/'));
  }
  await evaluate('document.querySelector(".island-trigger").click()');
  await delay(650);
  assert.equal(await evaluate('document.querySelector(".island-content").inert'), true);
  await evaluate('document.querySelector(".island-trigger").click()');
  await delay(650);
  await fs.writeFile(path.join(qa, 'desktop-media.png'), (await overlay.webContents.capturePage()).toPNG());
  console.log('PASS: glass keeps dark settings, Windows media, accessible collapse');
  await evaluate(`document.querySelector('.island-module-tabs [title="Recording"]').click()`);
  await until(() => evaluate('Boolean(document.querySelector(".screen-recording-module"))'), 'recording view transition');
  await evaluate('document.querySelector(".screen-recording-module .module-action").click()');
  await until(() => evaluate('document.querySelector(\'[aria-label="Capture source"]\').options.length > 1'), 'capture sources');
  const nativeHandle = overlay.getNativeWindowHandle();
  const handle = (nativeHandle.length === 8 ? nativeHandle.readBigUInt64LE() : BigInt(nativeHandle.readUInt32LE())).toString();
  const source = await evaluate(`Array.from(document.querySelector('[aria-label="Capture source"]').options).find(option => option.value.split(':')[1] === ${JSON.stringify(handle)})?.value`);
  assert.ok(source, 'our own overlay is available as a capture source');
  await evaluate(`(() => { const select = document.querySelector('[aria-label="Capture source"]'); const setter = Object.getOwnPropertyDescriptor(HTMLSelectElement.prototype, 'value').set; setter.call(select, ${JSON.stringify(source)}); select.dispatchEvent(new Event('change', { bubbles: true })); })()`);
  await delay(100);
  await evaluate('document.querySelector(".screen-recording-module .primary").click()');
  await until(() => evaluate('document.querySelector(".screen-recording-module .primary").textContent.includes("Остановить")'), 'native screen recording started');
  await until(async () => { try { return (await fs.stat(recordingPath)).size > 100; } catch { return false; } }, 'recording receives video frames');
  await evaluate('document.querySelector(".screen-recording-module .primary").click()');
  await until(() => evaluate('document.querySelector(".screen-recording-module .primary").textContent.includes("Начать")'), 'native recording finalized');
  assert.equal(await evaluate('document.querySelector(".screen-recording-module [role=alert]")?.textContent ?? null'), null, 'recording has no error');
  const recorded = await fs.readFile(recordingPath);
  assert.ok(recorded.length > 100, 'saved video has content');
  assert.equal(recorded.subarray(0, 4).toString('hex'), '1a45dfa3', 'saved recording is WebM');
  console.log('PASS: actual window capture, MediaRecorder, streamed WebM save and stop');
  await evaluate(`document.querySelector('.island-module-tabs [title="Часы"]').click()`);
  await delay(200);
  await evaluate('document.querySelector(".island-trigger").click()');
  await delay(6200);
  assert.equal(overlay.isVisible(), true, 'overlay remains visible after the former hide timeout');
  assert.equal(await evaluate('getComputedStyle(document.querySelector(".island-shell")).opacity'), '1');
  assert.equal(await evaluate('document.querySelector(".island-shell").classList.contains("clock-only")'), true);
  const compactClock = await evaluate('document.querySelector(".trigger-compact").innerText.trim()');
  assert.match(compactClock, /^\d{2}:\d{2}$/);
  assert.equal(await evaluate('document.querySelector(".trigger-compact .compact-leading") === null && document.querySelector(".trigger-compact .compact-dot") === null'), true);
  console.log('PASS: permanent idle clock, time only, no fading after inactivity');
  getSettings().close();
  console.log('Desktop smoke checks passed.');
  app.quit();
};
